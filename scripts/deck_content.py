def stats() -> dict:
    db = get_db()
    g = graph_repo.stats()
    s = {
        "kps": g.kps, "edges": g.edges, "tasks": g.tasks, "links": g.task_kp_links,
        "modules": g.modules,
        "students": db.scalar("SELECT COUNT(*) FROM student") or 0,
        "events": db.scalar("SELECT COUNT(*) FROM learning_event") or 0,
        "patterns": db.scalar("SELECT COUNT(*) FROM error_pattern") or 0,
        "instances": db.scalar("SELECT COUNT(*) FROM error_instance") or 0,
        "signals": db.scalar("SELECT COUNT(*) FROM project_signal") or 0,
        "projects": db.scalar("SELECT COUNT(*) FROM project") or 0,
        "escalations": db.scalar(
            "SELECT COUNT(*) FROM learning_event WHERE event_type='escalation'") or 0,
    }
    # 掌握的质量：实测数字直接进 PPT，避免讲的是一套、系统是另一套
    try:
        from packages.state import verification
        c = graph_repo.get_course("ML")
        v = verification.class_verification(c["id"], "实验班A") if c else {}
        s["v_mastered"] = v.get("n_mastered", 0)
        s["v_validated"] = v.get("n_validated", 0)
        s["v_rate"] = round(v.get("validated_rate", 0) * 100)
        s["v_due"] = v.get("n_due", 0)
    except Exception:
        s.update(v_mastered=0, v_validated=0, v_rate=0, v_due=0)
    return s


