def stats() -> dict:
    db, g = get_db(), graph_repo.stats()

    def q(sql: str, *a) -> int:
        return db.scalar(sql, a) or 0

    s = {
        "courses": g.courses, "kps": g.kps, "edges": g.edges,
        "tasks": g.tasks, "links": g.task_kp_links, "modules": g.modules,
        "students": q("SELECT COUNT(*) FROM student"),
        "events": q("SELECT COUNT(*) FROM learning_event"),
        "mastery_rows": q("SELECT COUNT(*) FROM mastery_state"),
        "patterns": q("SELECT COUNT(*) FROM error_pattern"),
        "instances": q("SELECT COUNT(*) FROM error_instance"),
        "questions": q("SELECT COUNT(*) FROM question"),
        "verified_q": q("SELECT COUNT(*) FROM question WHERE teacher_verified=1"),
        "projects": q("SELECT COUNT(*) FROM project"),
        "signals": q("SELECT COUNT(*) FROM project_signal"),
        "pending_cand": q("SELECT COUNT(*) FROM task_kp_candidate WHERE status='pending'"),
        "cross_edges": q(
            "SELECT COUNT(*) FROM prerequisite p"
            " JOIN knowledge_point a ON a.id=p.from_kp_id"
            " JOIN knowledge_point b ON b.id=p.to_kp_id"
            " WHERE a.course_id<>b.course_id"),
    }

    from packages.state import coverage

    prog = graph_repo.get_program(PROGRAM)
    m = coverage.program_map(PROGRAM, PROJECT) if prog else {}
    s.update(
        prog_name=prog["name"] if prog else "",
        prog_credit=graph_repo.program_credit_total(prog["id"]) if prog else 0,
        n_courses=m.get("n_courses", 0),
        n_touched=m.get("n_touched", 0),
        n_built=m.get("n_built", 0),
        pulled_total=m.get("pulled_total", 0),
        project_only=m.get("project_only_kps", 0),
        practice_course_name=m.get("practice_course_name", ""),
    )

    try:
        from packages.state import verification

        c = graph_repo.get_course("G18Z21022")
        v = verification.class_verification(c["id"], "实验班A") if c else {}
        s["v_mastered"] = v.get("n_mastered", 0)
        s["v_validated"] = v.get("n_validated", 0)
        s["v_rate"] = round(v.get("validated_rate", 0) * 100)
        s["v_due"] = v.get("n_due", 0)
    except Exception:
        s.update(v_mastered=0, v_validated=0, v_rate=0, v_due=0)

    # 测试用例数当场数出来。写死一个数字，加两个用例它就成了假话——
    # 而这份 PPT 通篇在说"每个数字都能当场核对"。
    s["tests"] = sum(
        f.read_text(encoding="utf-8").count("    def test_")
        for f in sorted((ROOT / "tests").glob("test_*.py")))
    return s


